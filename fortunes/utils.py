def get_star_info(month, day):
    stars = [
        (1, 20, "물병자리", "♒"), (2, 19, "물고기자리", "♓"), (3, 21, "양자리", "♈"),
        (4, 20, "황소자리", "♉"), (5, 21, "쌍둥이자리", "♊"), (6, 22, "게자리", "♋"),
        (7, 23, "사자자리", "♌"), (8, 23, "처녀자리", "♍"), (9, 24, "천칭자리", "♎"),
        (10, 23, "전갈자리", "♏"), (11, 23, "사수자리", "♐"), (12, 25, "염소자리", "♑")
    ]
    for m, d, name, icon in reversed(stars):
        if month > m or (month == m and day >= d): return name, icon
    return "염소자리", "♑"

def get_zodiac_info(year):
    zds = [("원숭이띠", "🐵"), ("닭띠", "🐔"), ("개띠", "🐶"), ("돼지띠", "🐷"),
           ("쥐띠", "🐭"), ("소띠", "🐮"), ("호랑이띠", "🐯"), ("토끼띠", "🐰"),
           ("용띠", "🐲"), ("뱀띠", "🐍"), ("말띠", "🐴"), ("양띠", "🐑")]
    return zds[year % 12]

